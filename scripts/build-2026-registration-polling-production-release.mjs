function runSql(sql) {
  return execFileSync(
    'docker',
    ['exec', '-i', 'supabase_db_public-office-watch', 'psql', '-X', '-qAt', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', '-d', 'postgres'],
    { input: sql, encoding: 'utf8', maxBuffer: 120e6 },
  ).trim();
}

function readRows(query, orderBy) {
  const output = runSql(`SELECT COALESCE(jsonb_agg(to_jsonb(row_data) ORDER BY ${orderBy}), '[]'::jsonb)::text
FROM (${query}) row_data;`);
  return JSON.parse(output);
}

