function chunksFor(rows, maximumBytes = 1_500_000) {
  const chunks = [];
  let current = [];
  let size = 2;
  for (const row of rows) {
    const serialized = JSON.stringify(row);
    const added = Buffer.byteLength(serialized) + (current.length ? 1 : 0);
    if (current.length && size + added > maximumBytes) {
      chunks.push(current);
      current = [];
      size = 2;
    }
    current.push(row);
    size += added;
  }
  if (current.length) chunks.push(current);
  return chunks;
}

