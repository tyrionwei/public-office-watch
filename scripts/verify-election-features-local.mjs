import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const rehearsal=process.argv.includes('--rehearsal');
const container=rehearsal?'supabase_db_public-office-watch-rehearsal':'supabase_db_public-office-watch';
const envFile=rehearsal?'apps/web/.env.rehearsal.local':'apps/web/.env.local';
const env=Object.fromEntries(fs.readFileSync(envFile,'utf8').split(/\r?\n/).filter(x=>x.includes('=')&&!x.startsWith('#')).map(x=>[x.slice(0,x.indexOf('=')),x.slice(x.indexOf('=')+1).trim().replace(/^["']|["']$/g,'')]));
const origin=env.VITE_SUPABASE_URL;
assert.equal(new URL(origin).port,rehearsal?'55321':'54321');
assert.ok(['localhost','127.0.0.1'].includes(new URL(origin).hostname));
const key=env.VITE_SUPABASE_ANON_KEY;
const query=(sql)=>JSON.parse(execFileSync('docker',['exec','-i',container,'psql','-X','-At','-v','ON_ERROR_STOP=1','-U','postgres','-d','postgres'],{input:sql,encoding:'utf8'}));
const permissions=query("select json_agg(x) from (select c.relname,c.relrowsecurity,has_table_privilege('anon',c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE') as anon_access,has_table_privilege('authenticated',c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE') as auth_access from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relname in ('candidate_lifecycle_events','polling_place_sources','polling_places','polling_place_neighborhoods')) x;");
assert.equal(permissions.length,4);
assert.ok(permissions.every(x=>x.relrowsecurity&&!x.anon_access&&!x.auth_access));
const request=async(method,args)=>{
 const response=await fetch(origin+'/rest/v1/rpc/'+method,{method:'POST',headers:{apikey:key,'Content-Type':'application/json','Content-Profile':'published'},body:JSON.stringify(args)});
 const payload=await response.json();assert.equal(response.status,200,JSON.stringify(payload));return payload;
};
const publicEvents=await request('candidate_lifecycle_for',{p_candidate_id:'08c553b1-617b-4c32-aef1-a26560edde7d'});
assert.equal(publicEvents.length,1);assert.equal(publicEvents[0].occurred_on,'2026-09-02');assert.equal(publicEvents[0].source_published_on,'2026-09-04');
assert.ok(!('event_data' in publicEvents[0]));assert.ok(!('source_hash' in publicEvents[0]));
const village=query("select to_json(village_code) from public.polling_places where station_no='0003' limit 1;");
const places=await request('polling_places_for_village',{p_event_key:'2026-local-general-election-day',p_village_code:village});
assert.equal(places.length,2);assert.deepEqual(places.map(x=>x.station_no),['0003','0004']);
assert.ok(places.find(x=>x.station_no==='0004').neighborhoods.includes(15));
assert.deepEqual(await request('polling_places_for_village',{p_event_key:'2022-local',p_village_code:village}),[]);
const visibilityTest=String.raw`BEGIN;
UPDATE public.candidates SET is_public=FALSE WHERE id='08c553b1-617b-4c32-aef1-a26560edde7d';
SET LOCAL ROLE anon;
DO $test$ BEGIN IF EXISTS (SELECT 1 FROM published.candidate_lifecycle_for('08c553b1-617b-4c32-aef1-a26560edde7d')) THEN RAISE EXCEPTION 'Private candidate event leaked from a stale published snapshot'; END IF; END; $test$;
RESET ROLE;
UPDATE public.candidates SET is_public=TRUE WHERE id='08c553b1-617b-4c32-aef1-a26560edde7d';
UPDATE public.candidate_lifecycle_events SET is_public=FALSE WHERE candidate_id='08c553b1-617b-4c32-aef1-a26560edde7d';
SET LOCAL ROLE anon;
DO $test$ BEGIN IF EXISTS (SELECT 1 FROM published.candidate_lifecycle_for('08c553b1-617b-4c32-aef1-a26560edde7d')) THEN RAISE EXCEPTION 'Private event leaked'; END IF; END; $test$;
RESET ROLE;
UPDATE public.polling_place_sources SET is_current=FALSE WHERE county_code='65000';
SET LOCAL ROLE anon;
DO $test$ BEGIN IF EXISTS (SELECT 1 FROM published.polling_places_for_village('2026-local-general-election-day','${village}')) THEN RAISE EXCEPTION 'Stale source leaked'; END IF; END; $test$;
ROLLBACK;`;
execFileSync('docker',['exec','-i',container,'psql','-X','-v','ON_ERROR_STOP=1','-U','postgres','-d','postgres'],{input:visibilityTest,encoding:'utf8'});
const report={environment:rehearsal?'rehearsal':'full-local',private_tables_blocked:true,private_events_blocked:true,private_candidates_blocked:true,
 stale_sources_blocked:true,event_scope_checked:true,registration_date_separate_from_publication:true,official_station_match:true};
fs.mkdirSync('tmp/polling-places-2026',{recursive:true});
fs.writeFileSync('tmp/polling-places-2026/'+report.environment+'-api-verification.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
