    affected_count INTEGER;
BEGIN
    UPDATE public.person_claims AS claim
    SET
        claim_value = repair.repaired_source,
        claim_json = pg_catalog.jsonb_set(
            pg_catalog.jsonb_set(
                pg_catalog.jsonb_set(
                    pg_catalog.jsonb_set(
                        COALESCE(claim.claim_json, '{}'::JSONB),
                        '{platformText}',
                        pg_catalog.to_jsonb(repair.repaired_source),
                        TRUE
                    ),
                    '{items}',
                    repair.repaired_items,
                    TRUE
                ),
                '{contentSplit}',
                COALESCE(claim.claim_json -> 'contentSplit', '{}'::JSONB)
                    || pg_catalog.jsonb_build_object(
                        'reviewStatus',
                        'reviewed',
                        'releaseQuality',
                        pg_catalog.jsonb_build_object(
                            'version',
                            'verified-platform-repair-20260907',
                            'reasonCodes',
                            '[]'::JSONB
                        )
                    ),
                TRUE
            ),
            '{platformQualityAudit}',
            COALESCE(claim.claim_json -> 'platformQualityAudit', '{}'::JSONB)
                || pg_catalog.jsonb_build_object(
                    'repairVersion',
                    'verified-platform-repair-20260907',
                    'repair',
                    repair.repair_method,
                    'classification',
                    'verified_repair'
                ),
            TRUE
        ),
        updated_at = pg_catalog.now()
    FROM verified_platform_repairs AS repair
    WHERE claim.id = repair.id
      AND claim.claim_type = 'platform'
      AND COALESCE(claim.claim_json ->> 'platformText', claim.claim_value) = repair.old_source
      AND claim.claim_json #>> '{contentSplit,reviewStatus}' = 'needs_review';

    GET DIAGNOSTICS affected_count = ROW_COUNT;
    IF affected_count <> 6 THEN
        RAISE EXCEPTION 'Expected to release 6 verified platform repairs, updated %', affected_count;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM verified_platform_repairs AS repair
        LEFT JOIN public.person_claims AS claim ON claim.id = repair.id
        WHERE claim.claim_value <> repair.repaired_source
           OR claim.claim_json ->> 'platformText' <> repair.repaired_source
           OR claim.claim_json -> 'items' <> repair.repaired_items
           OR claim.claim_json #>> '{contentSplit,reviewStatus}' <> 'reviewed'
           OR claim.claim_json #>> '{platformQualityAudit,classification}' <> 'verified_repair'
